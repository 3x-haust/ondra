/** one side of a file: `rev` null is the worktree (the new side), "fx-merge" the merged job's new side */
export function fixtureFileAt(rev: string | null, path: string): FileAt {
  const merged = rev === "fx-before" || rev === "fx-merge";
  const list = merged ? MERGED : OPEN;
  const newSide = rev === null || rev === "fx-merge";
  const f = list.find((x) => (newSide ? x.path === path : (x.old ?? x.path) === path));
  const side = f ? (newSide ? f.b : f.a) : null;
  if (side === null) return { text: null, size: 0, binary: false, missing: true, cut: false };
  if (side === "bin") return { text: null, size: 18_432, binary: true, missing: false, cut: false };
  return { text: side, size: side.length, binary: false, missing: false, cut: false };
}
