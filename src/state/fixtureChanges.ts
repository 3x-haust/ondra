const textOf = (s: string) => Text.of(s.replace(/\n$/, "").split("\n"));
/** a unified diff of one file, three lines around each change, as `git diff` writes it */
function unified(f: Fx, budget: number): { patch: string; add: number; del: number } {
  const a = f.old ?? f.path;
  let head = `diff --git a/${a} b/${f.path}\n`;
  if (f.status === "R") head += `similarity index 90%\nrename from ${f.old}\nrename to ${f.path}\n`;
  if (f.a === null) head += "new file mode 100644\n";
  if (f.b === null) head += "deleted file mode 100644\n";
  if (f.a === "bin" || f.b === "bin") return { patch: `${head}Binary files a/${a} and b/${f.path} differ\n`, add: 0, del: 0 };
  head += `--- ${f.a === null ? "/dev/null" : `a/${a}`}\n+++ ${f.b === null ? "/dev/null" : `b/${f.path}`}\n`;
  const A = f.a === null ? [] : f.a.replace(/\n$/, "").split("\n");
  const B = f.b === null ? [] : f.b.replace(/\n$/, "").split("\n");
  const ta = textOf(f.a ?? "");
  const tb = textOf(f.b ?? "");
  // changed line ranges (0-based, end exclusive) on each side
  // a position past the end (a change at the very end) is after the last line
  const before = (t: Text, p: number) => (p > t.length ? t.lines : t.lineAt(p).number - 1);
  const ranges = f.a === null ? [{ a0: 0, a1: 0, b0: 0, b1: B.length }] : f.b === null ? [{ a0: 0, a1: A.length, b0: 0, b1: 0 }]
    : Chunk.build(ta, tb).map((c) => ({
        a0: before(ta, c.fromA), a1: c.toA > c.fromA ? ta.lineAt(c.endA).number : before(ta, c.fromA),
        b0: before(tb, c.fromB), b1: c.toB > c.fromB ? tb.lineAt(c.endB).number : before(tb, c.fromB),
      }));
  let out = head;
  let add = 0;
  let del = 0;
  const C = 3;
  let i = 0;
  while (i < ranges.length) {
    let j = i;
    while (j + 1 < ranges.length && ranges[j + 1].a0 - ranges[j].a1 <= C * 2) j++;
    const sa = Math.max(0, ranges[i].a0 - C);
    const sb = Math.max(0, ranges[i].b0 - C);
    const ea = Math.min(A.length, ranges[j].a1 + C);
    const eb = Math.min(B.length, ranges[j].b1 + C);
    out += `@@ -${A.length ? sa + 1 : 0},${ea - sa} +${B.length ? sb + 1 : 0},${eb - sb} @@\n`;
    let pa = sa;
    for (let k = i; k <= j; k++) {
      const r = ranges[k];
      for (; pa < r.a0; pa++) out += ` ${A[pa]}\n`;
      for (let x = r.a0; x < r.a1; x++) (out += `-${A[x]}\n`), del++;
      for (let x = r.b0; x < r.b1; x++) {
        add++;
        if (out.length < budget) out += `+${B[x]}\n`;
      }
      pa = r.a1;
    }
    for (; pa < ea; pa++) out += ` ${A[pa]}\n`;
    i = j + 1;
  }
  return { patch: out, add, del };
}

const CAP = 400 * 1024;
function changesOf(list: Fx[], branch: string): GitChanges {
  let patch = "";
  const files: GitFile[] = [];
  for (const f of list) {
    const u = unified(f, CAP);
    if (patch.length < CAP) patch += u.patch;
    files.push({ path: f.path, add: u.add, del: u.del, status: f.status });
  }
  if (patch.length > CAP) patch = `${patch.slice(0, CAP)}\n… (diff truncated)\n`;
  return { isRepo: true, branch, files, patch };
}

