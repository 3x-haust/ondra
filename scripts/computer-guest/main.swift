// Install as /usr/local/libexec/ondra-computer-endpoint (root:wheel, 0755).
// State: /private/var/db/ondra-computer (root:wheel, 0755), immutable during a lease.
// provision.json (root:wheel, 0644):
// {"version":1,"taskId":"task","vmUuid":"lowercase UUID","hostUuid":"lowercase UUID","guestUid":501}
// boot.json (root:wheel, 0644), replaced by provisioning on every boot:
// {"version":1,"vmUuid":"lowercase UUID","bootNonce":"64 lowercase hex","bootSessionUuid":"lowercase kern.bootsessionuuid"}
// The nonce must be independently generated by the trusted lifecycle manager.
// /Users/ondra-computer is the dedicated guest account's home (guest UID, 0700).
// Native v1.1.0 binary + helper live in /usr/local/libexec/ondra-computer/1.1.0,
// root:wheel, 0755, under root-owned non-writable, non-symlink ancestors.
// CLI contract: https://github.com/vercel-labs/agent-desktop/tree/v1.1.0/src/cli_args
// Same-UID processes and root are trusted; this endpoint is not a VM lifecycle manager.

let stateDirectory = "/private/var/db/ondra-computer"
let guestHome = "/Users/ondra-computer"
let desktopDirectory = "/usr/local/libexec/ondra-computer/1.1.0"
let desktopBinary = desktopDirectory + "/agent-desktop"
let desktopHelper = desktopDirectory + "/agent-desktop-macos-helper"
let inputLimit = 256 * 1024
let outputLimit = 8 * 1024 * 1024
let screenshotLimit = 4 * 1024 * 1024
let uuidPattern = "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"

struct Refusal: Error {
    let code: String
    let delivery: String
    init(_ code: String, _ delivery: String = "not_delivered") {
        self.code = code
        self.delivery = delivery
    }
}

func require(_ condition: Bool, _ code: String) throws {
    if !condition { throw Refusal(code) }
}
func matches(_ value: String, _ pattern: String) -> Bool {
    guard let range = value.range(of: pattern, options: .regularExpression) else { return false }
    return range == value.startIndex..<value.endIndex
}
func fields(_ object: [String: Any], _ keys: [String]) -> Bool {
    Set(object.keys) == Set(keys)
}
func integer(_ value: Any?) -> Int? {
    guard let number = value as? NSNumber, CFGetTypeID(number) != CFBooleanGetTypeID(),
          number.doubleValue.isFinite, number.doubleValue == Double(number.int64Value),
          number.int64Value >= 0, number.int64Value <= Int64(Int32.max) else { return nil }
    return number.intValue
}
func object(_ data: Data) throws -> [String: Any] {
    guard let result = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
        throw Refusal("INVALID_JSON")
    }
    return result
}

func secureDirectory(_ path: String, owner: uid_t = 0, exactMode: mode_t? = nil) throws {
    var current = ""
    let parts = path.split(separator: "/")
    for (index, part) in parts.enumerated() {
        current += "/" + part
        var info = stat()
        let last = index == parts.count - 1
        try require(lstat(current, &info) == 0, "UNPROVISIONED_GUEST")
        try require(info.st_mode & S_IFMT == S_IFDIR && info.st_uid == (last ? owner : 0)
                    && info.st_mode & 0o022 == 0, "UNSAFE_DIRECTORY")
        if last, let mode = exactMode {
            try require(info.st_mode & 0o7777 == mode, "UNSAFE_DIRECTORY")
        }
    }
}

func secureFile(_ path: String, limit: Int, mode: mode_t = 0o644) throws -> Data {
    let fd = open(path, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
    try require(fd >= 0, "UNPROVISIONED_GUEST")
    defer { close(fd) }
    var info = stat()
    try require(fstat(fd, &info) == 0 && info.st_mode & S_IFMT == S_IFREG
                && info.st_uid == 0 && info.st_gid == 0 && info.st_mode & 0o7777 == mode
                && info.st_nlink == 1 && info.st_size > 0 && info.st_size <= limit, "UNSAFE_FILE")
    var data = Data()
    var bytes = [UInt8](repeating: 0, count: 16 * 1024)
    while true {
        let count = Darwin.read(fd, &bytes, min(bytes.count, limit + 1 - data.count))
        if count < 0 && errno == EINTR { continue }
        try require(count >= 0, "STATE_READ_ERROR")
        if count == 0 { return data }
        data.append(contentsOf: bytes.prefix(count))
        try require(data.count <= limit, "FILE_LIMIT")
    }
}

func hardwareUUID() throws -> String {
    let service = IOServiceGetMatchingService(kIOMainPortDefault, IOServiceMatching("IOPlatformExpertDevice"))
    try require(service != 0, "PLATFORM_IDENTITY_UNAVAILABLE")
    defer { IOObjectRelease(service) }
    guard let value = IORegistryEntryCreateCFProperty(service, "IOPlatformUUID" as CFString, kCFAllocatorDefault, 0)?.takeRetainedValue() as? String else {
        throw Refusal("PLATFORM_IDENTITY_UNAVAILABLE")
    }
    return value.lowercased()
}
func bootUUID() throws -> String {
    var size = 0
    try require(sysctlbyname("kern.bootsessionuuid", nil, &size, nil, 0) == 0 && size > 1 && size <= 128,
                "BOOT_IDENTITY_UNAVAILABLE")
    var buffer = [CChar](repeating: 0, count: size)
    try require(sysctlbyname("kern.bootsessionuuid", &buffer, &size, nil, 0) == 0, "BOOT_IDENTITY_UNAVAILABLE")
    return String(decoding: buffer.prefix { $0 != 0 }.map { UInt8(bitPattern: $0) }, as: UTF8.self).lowercased()
}

struct GuestIdentity {
    let taskId: String
    let vmUuid: String
    let bootNonce: String
    let guestUid: uid_t
    var response: [String: Any] { ["version": 1, "taskId": taskId, "vmUuid": vmUuid, "bootNonce": bootNonce] }
}

func validateIdentity(_ provision: [String: Any], _ boot: [String: Any], actualUUID: String,
                      currentBoot: String, uid: uid_t, effectiveUid: uid_t) throws -> GuestIdentity {
    try require(fields(provision, ["version", "taskId", "vmUuid", "hostUuid", "guestUid"])
                && fields(boot, ["version", "vmUuid", "bootNonce", "bootSessionUuid"])
                && integer(provision["version"]) == 1 && integer(boot["version"]) == 1, "INVALID_PROVISION")
    guard let task = provision["taskId"] as? String, matches(task, "^[a-zA-Z0-9_-]{1,128}$"),
          let vm = provision["vmUuid"] as? String, matches(vm, uuidPattern),
          let host = provision["hostUuid"] as? String, matches(host, uuidPattern),
          let guestUid = integer(provision["guestUid"]), guestUid >= 501,
          let nonce = boot["bootNonce"] as? String, matches(nonce, "^[0-9a-f]{64}$"),
          let bootId = boot["bootSessionUuid"] as? String, matches(bootId, uuidPattern) else {
        throw Refusal("INVALID_PROVISION")
    }
    try require(vm != host && vm == actualUUID && boot["vmUuid"] as? String == vm, "GUEST_UUID_MISMATCH")
    try require(bootId == currentBoot, "STALE_BOOT_IDENTITY")
    try require(uid == uid_t(guestUid) && effectiveUid == uid && uid != 0, "GUEST_USER_MISMATCH")
    return GuestIdentity(taskId: task, vmUuid: vm, bootNonce: nonce, guestUid: uid)
}

func loadIdentity() throws -> GuestIdentity {
    try secureDirectory(stateDirectory, exactMode: 0o755)
    let provision = try object(secureFile(stateDirectory + "/provision.json", limit: 4096))
    let boot = try object(secureFile(stateDirectory + "/boot.json", limit: 4096))
    let identity = try validateIdentity(provision, boot, actualUUID: hardwareUUID(), currentBoot: bootUUID(),
                                        uid: getuid(), effectiveUid: geteuid())
    try secureDirectory(guestHome, owner: identity.guestUid, exactMode: 0o700)
    guard let account = getpwuid(identity.guestUid), String(cString: account.pointee.pw_dir) == guestHome else {
        throw Refusal("GUEST_HOME_MISMATCH")
    }
    return identity
}

func validateRequest(_ request: [String: Any]) throws -> String {
    guard integer(request["version"]) == 1, let op = request["op"] as? String,
          let id = request["requestId"] as? String, matches(id, uuidPattern) else {
        throw Refusal("INVALID_REQUEST")
    }
    let expected = op == "identity" ? ["version", "op", "requestId"]
        : ["version", "op", "requestId", "taskId", "vmUuid", "bootNonce", "argv"]
    try require((op == "identity" || op == "exec") && fields(request, expected), "INVALID_REQUEST")
    return op
}

func validateClaims(_ request: [String: Any], _ identity: GuestIdentity) throws {
    try require(request["taskId"] as? String == identity.taskId && request["vmUuid"] as? String == identity.vmUuid
                && request["bootNonce"] as? String == identity.bootNonce, "GUEST_IDENTITY_MISMATCH")
}

func validApp(_ value: String) -> Bool {
    !value.isEmpty && value.utf8.count <= 512 && !value.hasPrefix("-")
        && value == value.trimmingCharacters(in: .whitespacesAndNewlines)
        && value.rangeOfCharacter(from: .controlCharacters) == nil && !value.contains("/")
}

// A deliberately narrow grammar; no passthrough flags or caller-selected output paths.
func allowedArguments(_ input: Any?) throws -> [String] {
    guard let argv = input as? [String], !argv.isEmpty, argv.count <= 16,
          argv.allSatisfy({ !$0.contains("\0") && $0.utf8.count <= 65536 }) else { throw Refusal("INVALID_ARGV") }
    if argv == ["session", "start", "--no-trace"] { return argv }
    try require(argv.count >= 4 && argv[0] == "--session" && matches(argv[1], "^[A-Za-z0-9_-]{1,256}$"), "INVALID_ARGV")
    let args = Array(argv.dropFirst(2))
    let command = args[0]
    let refPattern = "^@s[A-Za-z0-9_-]{1,255}:e[1-9][0-9]{0,9}$"
    switch command {
    case "session":
        try require(args == ["session", "end", argv[1]], "INVALID_ARGV")
    case "launch":
        try require(args.count == 2 && validApp(args[1]), "INVALID_ARGV")
    case "snapshot", "screenshot":
        try require(args.count == 3 && args[1] == "--app" && validApp(args[2]), "INVALID_ARGV")
    case "click":
        try require(args.count == 2 && matches(args[1], refPattern), "INVALID_ARGV")
    case "set-value":
        try require(args.count == 4 && matches(args[1], refPattern) && args[2] == "--", "INVALID_ARGV")
    case "press":
        try require(args.count == 4 && args[2] == "--app" && validApp(args[3]), "INVALID_ARGV")
        let keys = args[1].split(separator: "+", omittingEmptySubsequences: false).map(String.init)
        let modifiers = Array(keys.dropLast())
        try require(keys.count <= 5 && Set(modifiers).count == modifiers.count
                    && modifiers.allSatisfy({ ["cmd", "ctrl", "alt", "shift"].contains($0) })
                    && matches(keys.last ?? "", "^(?:[a-zA-Z0-9]|return|escape|tab|space|delete|up|down|left|right|f[1-9]|f1[0-2])$"), "INVALID_ARGV")
    default: throw Refusal("INVALID_ARGV")
    }
    return argv
}

func verifyDesktop() throws {
    try secureDirectory(desktopDirectory)
    #if arch(arm64)
    let binaryHash = "a89c781a3b2cf29bc0467c30a4e1063b6f564858540f2dc58a75c79ce2c9d9f3"
    let helperHash = "d81e5aa7ad8edb0e3eda72f010b1947ce7d6ad6d6d4ae95a69f4cce39bbbfe63"
    #elseif arch(x86_64)
    let binaryHash = "bfbb387446e615687dfe345158f7ac1e37197f5de203fa36bb621e474e016d77"
    let helperHash = "e32196af41669f531cb1d7779a84e53e865c6c05d224b9dc30239b749906e865"
    #else
    throw Refusal("UNSUPPORTED_ARCHITECTURE")
    #endif
    for (path, digest) in [(desktopBinary, binaryHash), (desktopHelper, helperHash)] {
        let data = try secureFile(path, limit: 128 * 1024 * 1024, mode: 0o755)
        let actual = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        try require(actual == digest, "DESKTOP_VERSION_MISMATCH")
    }
}

func readRequest() throws -> Data {
    let deadline = ProcessInfo.processInfo.systemUptime + 5
    var data = Data()
    var bytes = [UInt8](repeating: 0, count: 8192)
    while true {
        let remaining = deadline - ProcessInfo.processInfo.systemUptime
        try require(remaining > 0, "INPUT_TIMEOUT")
        var descriptor = pollfd(fd: STDIN_FILENO, events: Int16(POLLIN), revents: 0)
        let ready = poll(&descriptor, 1, Int32(max(1, remaining * 1000)))
        if ready < 0 && errno == EINTR { continue }
        try require(ready > 0 && descriptor.revents & Int16(POLLNVAL | POLLERR) == 0, "INPUT_TIMEOUT")
        let count = Darwin.read(STDIN_FILENO, &bytes, bytes.count)
        if count < 0 && errno == EINTR { continue }
        try require(count >= 0, "INPUT_ERROR")
        if count == 0 { return data }
        data.append(contentsOf: bytes.prefix(count))
        try require(data.count <= inputLimit, "INPUT_LIMIT")
    }
}

// Only the endpoint chooses this private directory and the output basename.
final class ScreenshotCapture {
    let directory: String
    let directoryFD: Int32
    var path: String { directory + "/screenshot.png" }

    init(home: String = guestHome) throws {
        var template = Array((home + "/.ondra-capture-XXXXXX").utf8CString)
        guard mkdtemp(&template) != nil else { throw Refusal("SCREENSHOT_DIRECTORY_ERROR") }
        directory = String(decoding: template.prefix { $0 != 0 }.map { UInt8(bitPattern: $0) }, as: UTF8.self)
        directoryFD = open(directory, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        if directoryFD < 0 {
            rmdir(directory)
            throw Refusal("SCREENSHOT_DIRECTORY_ERROR")
        }
    }

    deinit {
        unlinkat(directoryFD, "screenshot.png", 0)
        close(directoryFD)
        rmdir(directory)
    }

    func arguments(_ argv: [String]) throws -> [String] {
        let validated = try allowedArguments(argv)
        try require(validated.count == 5 && validated[2] == "screenshot", "INVALID_ARGV")
        return validated + [path]
    }
}

func screenshotImage(directoryFD: Int32, owner: uid_t) throws -> [String: Any] {
    func check(_ condition: Bool, _ code: String) throws {
        if !condition { throw Refusal(code, "unknown") }
    }
    var directory = stat()
    try check(fstat(directoryFD, &directory) == 0 && directory.st_mode & S_IFMT == S_IFDIR
              && directory.st_uid == owner && directory.st_mode & 0o7777 == 0o700, "UNSAFE_SCREENSHOT_DIRECTORY")
    let fd = openat(directoryFD, "screenshot.png", O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
    try check(fd >= 0, "SCREENSHOT_READ_ERROR")
    defer { close(fd) }
    var info = stat()
    try check(fstat(fd, &info) == 0 && info.st_mode & S_IFMT == S_IFREG && info.st_uid == owner
              && info.st_mode & 0o7777 == 0o600 && info.st_nlink == 1, "UNSAFE_SCREENSHOT_FILE")
    try check(info.st_size > 0 && info.st_size <= screenshotLimit, "SCREENSHOT_LIMIT")
    var data = Data()
    var bytes = [UInt8](repeating: 0, count: 16 * 1024)
    while true {
        let count = Darwin.read(fd, &bytes, min(bytes.count, screenshotLimit + 1 - data.count))
        if count < 0 && errno == EINTR { continue }
        try check(count >= 0, "SCREENSHOT_READ_ERROR")
        if count == 0 { break }
        data.append(contentsOf: bytes.prefix(count))
        try check(data.count <= screenshotLimit, "SCREENSHOT_LIMIT")
    }
    try check(data.count == info.st_size, "SCREENSHOT_CHANGED")
    try check(data.starts(with: [137, 80, 78, 71, 13, 10, 26, 10]), "INVALID_SCREENSHOT_PNG")
    let options = [kCGImageSourceShouldCache: false] as CFDictionary
    guard let source = CGImageSourceCreateWithData(data as CFData, options),
          CGImageSourceGetType(source) as String? == "public.png", CGImageSourceGetCount(source) == 1,
          CGImageSourceGetStatus(source) == .statusComplete,
          let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, options) as? [CFString: Any],
          let width = integer(properties[kCGImagePropertyPixelWidth]),
          let height = integer(properties[kCGImagePropertyPixelHeight]) else {
        throw Refusal("INVALID_SCREENSHOT_PNG", "unknown")
    }
    try check(width > 0 && height > 0 && width <= 8192 && height <= 8192
              && width * height <= 16 * 1024 * 1024, "SCREENSHOT_DIMENSION_LIMIT")
    let decodeOptions = [kCGImageSourceShouldCache: true, kCGImageSourceShouldCacheImmediately: true] as CFDictionary
    guard let image = CGImageSourceCreateImageAtIndex(source, 0, decodeOptions),
          image.width == width && image.height == height,
          CGImageSourceGetStatusAtIndex(source, 0) == .statusComplete else {
        throw Refusal("INVALID_SCREENSHOT_PNG", "unknown")
    }
    return ["mimeType": "image/png", "data": data.base64EncodedString(), "width": width, "height": height]
}

// Once started, timeout/IO/exit failures are ambiguous. Never replay a command.
func executeDesktop(_ argv: [String]) throws -> Any {
    let capture = argv.count == 5 && argv[2] == "screenshot" ? try ScreenshotCapture() : nil
    defer { withExtendedLifetime(capture) {} }
    let child = Process()
    child.executableURL = URL(fileURLWithPath: desktopBinary)
    child.arguments = try capture?.arguments(argv) ?? argv
    child.currentDirectoryURL = URL(fileURLWithPath: guestHome)
    child.environment = ["HOME": guestHome, "PATH": "/usr/bin:/bin", "LANG": "en_US.UTF-8",
                         "AGENT_DESKTOP_MACOS_HELPER_PATH": desktopHelper]
    child.standardInput = FileHandle.nullDevice
    let output = Pipe(), errors = Pipe()
    child.standardOutput = output
    child.standardError = errors
    let handles = [output.fileHandleForReading, errors.fileHandleForReading]
    defer { for handle in handles { try? handle.close() } }
    for handle in handles {
        let fd = handle.fileDescriptor
        try require(fcntl(fd, F_SETFL, fcntl(fd, F_GETFL) | O_NONBLOCK) == 0, "PIPE_ERROR")
    }
    do { try child.run() } catch { throw Refusal("SPAWN_ERROR") }
    try? output.fileHandleForWriting.close()
    try? errors.fileHandleForWriting.close()
    defer { if child.isRunning { kill(child.processIdentifier, SIGKILL) } }
    let deadline = ProcessInfo.processInfo.systemUptime + 25
    var stdout = Data(), total = 0
    var ended = [false, false]
    var bytes = [UInt8](repeating: 0, count: 16 * 1024)
    while child.isRunning || !ended.allSatisfy({ $0 }) {
        if ProcessInfo.processInfo.systemUptime >= deadline { throw Refusal("DESKTOP_TIMEOUT", "unknown") }
        var descriptors = handles.enumerated().map { index, handle in
            pollfd(fd: ended[index] ? -1 : handle.fileDescriptor, events: Int16(POLLIN), revents: 0)
        }
        let ready = poll(&descriptors, nfds_t(descriptors.count), 20)
        if ready < 0 && errno != EINTR { throw Refusal("DESKTOP_IO_ERROR", "unknown") }
        for index in 0..<handles.count where !ended[index] {
            let count = Darwin.read(handles[index].fileDescriptor, &bytes, bytes.count)
            if count == 0 { ended[index] = true }
            else if count > 0 {
                total += count
                if total > outputLimit - 4096 { throw Refusal("OUTPUT_LIMIT", "unknown") }
                if index == 0 { stdout.append(contentsOf: bytes.prefix(count)) }
            } else if errno != EAGAIN && errno != EINTR { throw Refusal("DESKTOP_IO_ERROR", "unknown") }
        }
    }
    return try desktopResult(stdout, status: child.terminationStatus, normalExit: child.terminationReason == .exit,
                             command: argv.first == "--session" ? argv[2] : argv[0], capture: capture)
}

func desktopResult(_ stdout: Data, status: Int32, normalExit: Bool, command: String,
                   capture: ScreenshotCapture? = nil) throws -> Any {
    guard normalExit else { throw Refusal("DESKTOP_SIGNAL", "unknown") }
    guard let result = try? object(stdout), result["version"] as? String == "2.6",
          let ok = result["ok"] as? NSNumber, CFGetTypeID(ok) == CFBooleanGetTypeID(),
          result["command"] as? String == command,
          result[ok.boolValue ? "data" : "error"] is [String: Any] else {
        throw Refusal("INVALID_DESKTOP_RESPONSE", "unknown")
    }
    // v1.1.0: 0 success, 1 operational error, 2 structured argument error.
    guard ok.boolValue ? status == 0 : [1, 2].contains(status) else {
        throw Refusal("DESKTOP_EXIT", "unknown")
    }
    if command == "screenshot" && ok.boolValue {
        guard let capture else { throw Refusal("INVALID_SCREENSHOT_CONTEXT", "unknown") }
        return ["version": "2.6", "command": "screenshot", "ok": true,
                "data": ["image": try screenshotImage(directoryFD: capture.directoryFD, owner: geteuid())]]
    }
    return result
}

