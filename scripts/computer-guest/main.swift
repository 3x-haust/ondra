@main
struct Endpoint {
    static func main() {
        umask(0o077)
        do {
            try require(CommandLine.arguments.count == 1, "INVALID_INVOCATION")
            let request = try object(readRequest())
            let op = try validateRequest(request)
            let identity = try loadIdentity()
            var response = identity.response
            response["requestId"] = request["requestId"]
            if op == "exec" {
                try validateClaims(request, identity)
                let argv = try allowedArguments(request["argv"])
                try verifyDesktop()
                // Detect a lifecycle transition between admission and spawn.
                let fresh = try loadIdentity()
                try validateClaims(request, fresh)
                response["result"] = try executeDesktop(argv)
            }
            let data = try JSONSerialization.data(withJSONObject: response, options: [.sortedKeys])
            if data.count + 1 > outputLimit { throw Refusal("OUTPUT_LIMIT", "unknown") }
            FileHandle.standardOutput.write(data + Data([10]))
        } catch {
            let refusal = error as? Refusal ?? Refusal("ENDPOINT_ERROR", "unknown")
            let payload: [String: Any] = ["version": 1, "error": ["code": refusal.code, "delivery": refusal.delivery, "retry": "never"]]
            if let data = try? JSONSerialization.data(withJSONObject: payload, options: [.sortedKeys]) {
                FileHandle.standardError.write(data + Data([10]))
            }
            exit(refusal.delivery == "not_delivered" ? 64 : 70)
        }
    }
}
